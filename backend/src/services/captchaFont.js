export const CAPTCHA_CHARSET = Object.keys(G).join("");
/** list of lit cell centres for a char: [{x,y}] in glyph units (0..5, 0..7) */
export function glyphCells(ch) {
  const rows = G[ch];
  const cells = [];
  rows.forEach((row, y) =>
    [...row].forEach((bit, x) => {
      if (bit === "1") cells.push({ x: x + 0.5, y: y + 0.5 });
    }),
  );
  return cells;
}
